constexpr std::size_t kType9InitCount = sizeof(kType9Init) / sizeof(kType9Init[0]);

// Fills caller-provided storage that stays alive across esp_lcd_panel_init().
// The data pointers refer to the constexpr table, which has static storage.
inline std::size_t build_init_commands(st7701_lcd_init_cmd_t* out, std::size_t capacity) {
    if (out == nullptr || capacity < kType9InitCount) {
        return 0;
    }
    for (std::size_t i = 0; i < kType9InitCount; ++i) {
        out[i].cmd = static_cast<int>(kType9Init[i].cmd);
        out[i].data = kType9Init[i].data;
        out[i].data_bytes = kType9Init[i].length;
        out[i].delay_ms = kType9Init[i].delay_ms;
    }
    return kType9InitCount;
}

