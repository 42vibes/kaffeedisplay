#!/usr/bin/env python3
"""Embed the built admin SPA into a C++ table for the firmware.

The generated files are build products and stay out of git:

    firmware/components/webassets/generated/web_assets.cpp
    firmware/components/webassets/generated/web_assets_generated.hpp

The public interface lives in
``firmware/components/webassets/include/kaffee/web_assets.hpp``. The ``api``
component only has to depend on the ``webassets`` component.

Every payload is gzip-compressed with a fixed mtime and level so repeated runs
on different machines produce byte-identical output. ``--check`` verifies that
the generated files match the current ``web/dist`` without writing anything.
"""

from __future__ import annotations

import argparse
import gzip
import io
import json
import sys
from pathlib import Path

MAX_GZIP_BYTES = 400 * 1024

MIME_TYPES = {
    ".avif": "image/avif",
    ".css": "text/css; charset=utf-8",
    ".csv": "text/csv; charset=utf-8",
    ".gif": "image/gif",
    ".htm": "text/html; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".ico": "image/x-icon",
    ".jpeg": "image/jpeg",
    ".jpg": "image/jpeg",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".map": "application/json; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ttf": "font/ttf",
    ".txt": "text/plain; charset=utf-8",
    ".wasm": "application/wasm",
    ".webmanifest": "application/manifest+json",
    ".webp": "image/webp",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".xml": "application/xml",
}

IGNORED_NAMES = {".DS_Store", "Thumbs.db"}

DEFAULT_DIST = Path("web/dist")
DEFAULT_OUT = Path("firmware/components/webassets/generated")


def gzip_bytes(data: bytes) -> bytes:
    """Deterministic gzip: mtime 0, no filename, fixed compression level."""
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return buffer.getvalue()


def c_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def collect(dist: Path) -> list[tuple[str, str, bytes, int]]:
    if not dist.is_dir():
        raise SystemExit(f"embed_web: {dist} does not exist; run 'make web' first")
    assets: list[tuple[str, str, bytes, int]] = []
    for path in sorted(dist.rglob("*")):
        if not path.is_file() or path.name in IGNORED_NAMES:
            continue
        relative = path.relative_to(dist).as_posix()
        if relative.startswith("."):
            continue
        mime = MIME_TYPES.get(path.suffix.lower(), "application/octet-stream")
        raw = path.read_bytes()
        compressed = gzip_bytes(raw)
        assets.append(("/" + relative, mime, compressed, len(raw)))
    if not assets:
        raise SystemExit(f"embed_web: {dist} contains no files")
    return assets


def render_cpp(assets: list[tuple[str, str, bytes, int]]) -> str:
    lines = [
        "// Generated by tools/embed_web.py -- do not edit.",
        "// Input: web/dist. Regenerate with: python3 tools/embed_web.py",
        '#include "kaffee/web_assets.hpp"',
        "#include <string>",
        "",
        "namespace kaffee::web {",
        "namespace {",
        "",
    ]
    for index, (_path, _mime, data, _raw_size) in enumerate(assets):
        lines.append(f"constexpr std::uint8_t kAsset{index}[] = {{")
        for offset in range(0, len(data), 16):
            chunk = data[offset : offset + 16]
            lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
        lines.append("};")
        lines.append("")

    lines.append("constexpr WebAsset kAssets[] = {")
    for index, (path, mime, data, raw_size) in enumerate(assets):
        lines.append(
            "    {"
            f"{c_string(path)}, {c_string(mime)}, kAsset{index}, "
            f"{len(data)}, true, {raw_size}"
            "},"
        )
    lines.append("};")
    lines.append(
        "constexpr std::size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);"
    )
    lines += [
        "",
        "std::string normalize(std::string_view path) {",
        "    const auto query = path.find_first_of(\"?#\");",
        "    if (query != std::string_view::npos) {",
        "        path = path.substr(0, query);",
        "    }",
        "    std::string result(path);",
        "    if (result.empty()) {",
        '        result = "/";',
        "    }",
        "    if (result.front() != '/') {",
        '        result.insert(result.begin(), \'/\');',
        "    }",
        '    if (result == "/") {',
        '        result = "/index.html";',
        "    } else if (result.back() == '/') {",
        '        result += "index.html";',
        "    }",
        "    return result;",
        "}",
        "",
        "}  // namespace",
        "",
        "const WebAsset* assets() {",
        "    return kAssets;",
        "}",
        "",
        "std::size_t asset_count() {",
        "    return kAssetCount;",
        "}",
        "",
        "const WebAsset* find(std::string_view path) {",
        "    const std::string key = normalize(path);",
        "    for (std::size_t index = 0; index < kAssetCount; ++index) {",
        "        if (key == kAssets[index].path) {",
        "            return &kAssets[index];",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace kaffee::web",
        "",
    ]
    return "\n".join(lines)


def render_header(assets: list[tuple[str, str, bytes, int]]) -> str:
    return "\n".join(
        [
            "// Generated by tools/embed_web.py -- do not edit.",
            "#pragma once",
            "",
            "#include <cstddef>",
            "#include <cstdint>",
            "",
            "namespace kaffee::web {",
            "",
            "// Number of embedded assets at build time (0 for the stub component).",
            f"constexpr std::size_t kEmbeddedAssetCount = {len(assets)};",
            f"constexpr std::size_t kEmbeddedExpandedBytes = {sum(raw for _, _, _, raw in assets)};",
            f"constexpr std::size_t kEmbeddedGzipBytes = {sum(len(data) for _, _, data, _ in assets)};",
            "",
            "}  // namespace kaffee::web",
            "",
        ]
    )


def write_if_changed(path: Path, content: str) -> bool:
    encoded = content.encode("utf-8")
    if path.exists() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", type=Path, default=DEFAULT_DIST, help="Vite output directory")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="generated output directory")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that generated files are current instead of writing them",
    )
    parser.add_argument(
        "--allow-oversize",
        action="store_true",
        help=f"do not fail when gzip assets exceed {MAX_GZIP_BYTES // 1024} KiB",
    )
    args = parser.parse_args()

    assets = collect(args.dist)
    total_gzip = sum(len(data) for _, _, data, _ in assets)
    total_raw = sum(raw for _, _, _, raw in assets)

    files = {
        args.out / "web_assets.cpp": render_cpp(assets),
        args.out / "web_assets_generated.hpp": render_header(assets),
        args.out / "manifest.json": json.dumps(
            {
                "assets": [
                    {
                        "path": path,
                        "mime": mime,
                        "gzip_bytes": len(data),
                        "original_bytes": raw,
                    }
                    for path, mime, data, raw in assets
                ],
                "gzip_bytes": total_gzip,
                "original_bytes": total_raw,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
    }

    if args.check:
        stale = [str(path) for path, content in files.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            print("embed_web: generated assets are stale:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            print("Run: python3 tools/embed_web.py", file=sys.stderr)
            return 1
    else:
        changed = [str(path) for path, content in files.items() if write_if_changed(path, content)]
        for path in changed:
            print(f"embed_web: wrote {path}")

    print(
        f"embed_web: {len(assets)} assets, gzip {total_gzip / 1024:.1f} KiB "
        f"(raw {total_raw / 1024:.1f} KiB)"
    )
    if total_gzip > MAX_GZIP_BYTES and not args.allow_oversize:
        print(
            f"embed_web: ERROR gzip assets exceed the {MAX_GZIP_BYTES // 1024} KiB budget",
            file=sys.stderr,
        )
        return 1
    for path, _mime, data, _raw in assets:
        print(f"  {len(data):>8}  {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
