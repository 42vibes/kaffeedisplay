#!/usr/bin/env python3
"""Embed the built admin SPA into a C++ table for the firmware.

The generated files are build products and stay out of git:

    firmware/components/webassets/generated/web_assets_generated.inc
    firmware/components/webassets/generated/web_assets_generated.hpp

The public interface lives in
``firmware/components/webassets/include/kaffee/web_assets.hpp`` and matches the
``kaffee::api::Asset`` / ``kaffee_web_asset_lookup()`` adapter expected by
``components/api/src/api_assets.cpp``. Both raw and gzip payloads are embedded.

Every payload is gzip-compressed with a fixed mtime and level so repeated runs
on different machines produce byte-identical output. ``--check`` verifies that
the generated files match the current ``web/dist`` without writing anything.
"""

from __future__ import annotations

import argparse
import gzip
import io
import json
import sys
from pathlib import Path

MAX_GZIP_BYTES = 400 * 1024

MIME_TYPES = {
    ".avif": "image/avif",
    ".css": "text/css; charset=utf-8",
    ".csv": "text/csv; charset=utf-8",
    ".gif": "image/gif",
    ".htm": "text/html; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".ico": "image/x-icon",
    ".jpeg": "image/jpeg",
    ".jpg": "image/jpeg",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".map": "application/json; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ttf": "font/ttf",
    ".txt": "text/plain; charset=utf-8",
    ".wasm": "application/wasm",
    ".webmanifest": "application/manifest+json",
    ".webp": "image/webp",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".xml": "application/xml",
}

IGNORED_NAMES = {".DS_Store", "Thumbs.db"}

DEFAULT_DIST = Path("web/dist")
DEFAULT_OUT = Path("firmware/components/webassets/generated")
ENTRY_SOURCE = Path("firmware/components/webassets/src/web_assets.cpp")


def gzip_bytes(data: bytes) -> bytes:
    """Deterministic gzip: mtime 0, no filename, fixed compression level."""
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, compresslevel=9, mtime=0) as stream:
        stream.write(data)
    return buffer.getvalue()


def collect(dist: Path) -> list[tuple[str, str, bytes, bytes]]:
    if not dist.is_dir():
        raise SystemExit(f"embed_web: {dist} does not exist; run 'make web' first")
    assets: list[tuple[str, str, bytes, bytes]] = []
    for path in sorted(dist.rglob("*")):
        if not path.is_file() or path.name in IGNORED_NAMES:
            continue
        relative = path.relative_to(dist).as_posix()
        if relative.startswith("."):
            continue
        mime = MIME_TYPES.get(path.suffix.lower(), "application/octet-stream")
        raw = path.read_bytes()
        compressed = gzip_bytes(raw)
        assets.append(("/" + relative, mime, raw, compressed))
    if not assets:
        raise SystemExit(f"embed_web: {dist} contains no files")
    return assets


def emit_bytes(lines: list[str], name: str, data: bytes, nul_terminate: bool = False) -> None:
    """Emit a char array without any C string escaping ambiguities."""
    values = list(data)
    if nul_terminate:
        values.append(0)
    lines.append(f"constexpr char {name}[] = {{")
    if not values:
        # Never emit a zero-sized array; the table uses an explicit length.
        lines.append("    '\\x00',")
    else:
        for offset in range(0, len(values), 16):
            chunk = values[offset : offset + 16]
            # Separate character literals avoid C++ \x escape ambiguity and
            # make control bytes (and NUL in the MIME terminator) explicit.
            lines.append("    " + ", ".join(f"'\\x{byte:02x}'" for byte in chunk) + ",")
    lines.append("};")


def render_cpp(assets: list[tuple[str, str, bytes, bytes]]) -> str:
    lines = [
        "// Generated by tools/embed_web.py -- do not edit.",
        "// Input: web/dist. Regenerate with: python3 tools/embed_web.py",
        '#include "kaffee/web_assets.hpp"',
        "#include <string>",
        "",
        "namespace kaffee::api {",
        "namespace {",
        "",
    ]
    for index, (path, mime, raw, compressed) in enumerate(assets):
        emit_bytes(lines, f"kPath{index}", path.encode("utf-8"))
        emit_bytes(lines, f"kMime{index}", mime.encode("utf-8"), nul_terminate=True)
        emit_bytes(lines, f"kRaw{index}", raw)
        emit_bytes(lines, f"kGzip{index}", compressed)
        lines.append("")

    lines.append("constexpr Asset kAssets[] = {")
    for index, (path, _mime, raw, compressed) in enumerate(assets):
        immutable = "true" if path.startswith("/assets/") else "false"
        raw_size = len(raw)
        lines.append(
            "    {"
            f"std::string_view(kPath{index}, sizeof(kPath{index})), kMime{index}, "
            f"std::string_view(kRaw{index}, {raw_size}), "
            f"std::string_view(kGzip{index}, sizeof(kGzip{index})), {immutable}"
            "},"
        )
    lines.append("};")
    lines.append(
        "constexpr std::size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);"
    )
    lines += [
        "",
        "std::string normalize(std::string_view path) {",
        "    const auto query = path.find_first_of(\"?#\");",
        "    if (query != std::string_view::npos) {",
        "        path = path.substr(0, query);",
        "    }",
        "    std::string result(path);",
        "    if (result.empty()) {",
        '        result = "/";',
        "    }",
        "    if (result.front() != '/') {",
        '        result.insert(result.begin(), \'/\');',
        "    }",
        '    if (result == "/") {',
        '        result = "/index.html";',
        "    } else if (result.back() == '/') {",
        '        result += "index.html";',
        "    }",
        "    return result;",
        "}",
        "",
        "}  // namespace",
        "",
        "const Asset* kaffee_web_asset_lookup(std::string_view path) {",
        "    const std::string key = normalize(path);",
        "    for (std::size_t index = 0; index < kAssetCount; ++index) {",
        "        if (key == kAssets[index].path) {",
        "            return &kAssets[index];",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace kaffee::api",
        "",
        "namespace kaffee::web {",
        "",
        "const Asset* assets() {",
        "    return kaffee::api::kAssets;",
        "}",
        "",
        "std::size_t asset_count() {",
        "    return kaffee::api::kAssetCount;",
        "}",
        "",
        "const Asset* find(std::string_view path) {",
        "    return kaffee::api::kaffee_web_asset_lookup(path);",
        "}",
        "",
        "}  // namespace kaffee::web",
        "",
    ]
    return "\n".join(lines)


def render_header(assets: list[tuple[str, str, bytes, bytes]]) -> str:
    return "\n".join(
        [
            "// Generated by tools/embed_web.py -- do not edit.",
            "#pragma once",
            "",
            "#include <cstddef>",
            "",
            "namespace kaffee::web {",
            "",
            "// Number of embedded assets at build time (0 for the stub component).",
            f"constexpr std::size_t kEmbeddedAssetCount = {len(assets)};",
            f"constexpr std::size_t kEmbeddedExpandedBytes = {sum(len(raw) for _, _, raw, _ in assets)};",
            f"constexpr std::size_t kEmbeddedGzipBytes = {sum(len(gzip) for _, _, _, gzip in assets)};",
            "",
            "}  // namespace kaffee::web",
            "",
        ]
    )


def write_if_changed(path: Path, content: str) -> bool:
    encoded = content.encode("utf-8")
    if path.exists() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist", type=Path, default=DEFAULT_DIST, help="Vite output directory")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="generated output directory")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that generated files are current instead of writing them",
    )
    parser.add_argument(
        "--allow-oversize",
        action="store_true",
        help=f"do not fail when gzip assets exceed {MAX_GZIP_BYTES // 1024} KiB",
    )
    args = parser.parse_args()

    assets = collect(args.dist)
    total_gzip = sum(len(gzip) for _, _, _, gzip in assets)
    total_raw = sum(len(raw) for _, _, raw, _ in assets)

    files = {
        args.out / "web_assets_generated.inc": render_cpp(assets),
        args.out / "web_assets_generated.hpp": render_header(assets),
        args.out / "manifest.json": json.dumps(
            {
                "assets": [
                    {
                        "path": path,
                        "mime": mime,
                        "gzip_bytes": len(gzip),
                        "original_bytes": len(raw),
                    }
                    for path, mime, raw, gzip in assets
                ],
                "gzip_bytes": total_gzip,
                "original_bytes": total_raw,
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
    }

    if args.check:
        stale = [str(path) for path, content in files.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            print("embed_web: generated assets are stale:", file=sys.stderr)
            for path in stale:
                print(f"  {path}", file=sys.stderr)
            print("Run: python3 tools/embed_web.py", file=sys.stderr)
            return 1
    else:
        changed = [str(path) for path, content in files.items() if write_if_changed(path, content)]
        for path in changed:
            print(f"embed_web: wrote {path}")
        # The entry source uses __has_include, which Ninja cannot track when the
        # include file did not exist during the previous compile. Touch it so a
        # stub build recompiles after assets are generated.
        if ENTRY_SOURCE.exists():
            ENTRY_SOURCE.touch()

    print(
        f"embed_web: {len(assets)} assets, gzip {total_gzip / 1024:.1f} KiB "
        f"(raw {total_raw / 1024:.1f} KiB)"
    )
    if total_gzip > MAX_GZIP_BYTES and not args.allow_oversize:
        print(
            f"embed_web: ERROR gzip assets exceed the {MAX_GZIP_BYTES // 1024} KiB budget",
            file=sys.stderr,
        )
        return 1
    for path, _mime, _raw, gzip in assets:
        print(f"  {len(gzip):>8}  {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
